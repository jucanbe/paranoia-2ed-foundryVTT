import {readFile,writeFile} from "node:fs/promises";
import {resolve,dirname} from "node:path";
import {fileURLToPath} from "node:url";
import {messageKey} from "../module/i18n/index.mjs";
const root=resolve(dirname(fileURLToPath(import.meta.url)),"..");
const es=JSON.parse(await readFile(resolve(root,"lang/es.json"),"utf8"));
const catalogue={};
for(const pack of ["weapons","armor","equipment","robots","robot-programs","vehicles"]){
  for(const entry of JSON.parse(await readFile(resolve(root,`packs-source/${pack}.json`),"utf8"))){
    const fields={};
    function visit(value,path=""){
      if(typeof value==="string"&&Object.hasOwn(es.P2.Text,messageKey(value).split(".").at(-1)))fields[path]=messageKey(value);
      else if(value&&typeof value==="object")for(const [key,next]of Object.entries(value))visit(next,path?`${path}.${key}`:key);
    }
    visit(entry);catalogue[entry.catalogId]=fields;
  }
}
await writeFile(resolve(root,"module/i18n/catalogue-keys.mjs"),"// Generated by scripts/build-localization-catalogue.mjs. Translation fingerprints only.\nexport const CATALOGUE_KEYS="+JSON.stringify(catalogue,null,2)+";\n");
console.log(`Localization fingerprints generated for ${Object.keys(catalogue).length} catalogue entries.`);
